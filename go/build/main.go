package main

import core "dappco.re/go"

func main() {
	// Read package.json
	data := core.ReadFile("package.json")
	if !data.OK {
		core.Println("Error reading package.json, skipping version file generation.")
		return
	}

	// Parse package.json
	var pkg struct {
		Version string `json:"version"`
	}
	if result := core.JSONUnmarshal(data.Value.([]byte), &pkg); !result.OK {
		core.Println("Error parsing package.json, skipping version file generation.")
		return
	}

	// Create the version file
	content := core.Sprintf("package updater\n\n// Generated by go:generate. DO NOT EDIT.\n\nconst PkgVersion = %q\n", pkg.Version)
	if result := core.WriteFile("version.go", []byte(content), 0o644); !result.OK {
		core.Print(nil, "Error writing version file: %s", result.Error())
		return
	}

	core.Println("Generated version.go with version:", pkg.Version)
}
